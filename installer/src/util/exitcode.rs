//! 进程退出码 —— 对**调用方**的承诺，不是内部细节。
//!
//! 这里每个值都写在 README 的退出码表与 AGENTS.md 的调用方契约里：批量部署脚本、
//! winget、SCCM 按它们判断一次安装 / 卸载究竟算不算成功。改动任何一个都是破坏性变更。
//!
//! 集中在一处是有由来的：3010 原本是 `main.rs` 里的一个私有常量，于是**卸载器那个
//! 二进制**（`uninstaller_main.rs` —— ARP 的 `UninstallString` 指的正是它）根本够不着，
//! 它的静默路径就算判出「需要重启」也没有码可报。契约散落在各自的 main 里，
//! 迟早会分叉成两套。
#![allow(dead_code)] // 两个二进制各用其中一部分，另一个里就是「未使用」

/// 成功。
pub const SUCCESS: i32 = 0;

/// 失败。
pub const FAILURE: i32 = 1;

/// `ERROR_ACCESS_DENIED`：需要管理员权限，本次没有，且**不能**弹 UAC 去要。
///
/// 只出现在 `--silent`。静默的语义是「不产生任何 UI」，而 UAC 提示框就是 UI——
/// 弹它等于把一个无人值守的部署任务挂在那里等人点，直到超时。从前这条路是
/// 「弹 UAC + `exit(0)`」：调用方拿到的是「卸载成功」，而实际上卸载连开始都没开始。
pub const ACCESS_DENIED: i32 = 5;

/// `ERROR_INSTALL_ALREADY_RUNNING`：被单实例锁挡住，**本次什么都没做**，重试即可。
///
/// 沿用系统既有约定而不自造一个码：MSI 系的调用方本来就认得它。
pub const ALREADY_RUNNING: i32 = 1618;

/// `ERROR_SUCCESS_REBOOT_REQUIRED`：操作成功，但有文件被占用、需重启才能清理干净。
///
/// 取值沿用 Windows 约定，MSI 与 NSIS 都用它表达「装成功了，但请重启」。仅用于完全
/// 无界面的 `--silent`：那条路径没有窗口可以留给用户看提示，退出码是唯一能把这个
/// 事实交给调用方的通道。
///
/// **调用方须知**：把 `3010` 当作成功而非失败处理，再自行提示用户重启。
pub const REBOOT_REQUIRED: i32 = 3010;
